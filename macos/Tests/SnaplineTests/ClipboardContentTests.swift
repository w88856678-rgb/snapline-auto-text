import AppKit
import XCTest
@testable import Snapline

/// A private pasteboard keeps these tests away from the user's real clipboard.
@MainActor
func withTestPasteboard(_ body: (NSPasteboard) throws -> Void) rethrows {
    let pasteboard = NSPasteboard.withUniqueName()
    defer { pasteboard.releaseGlobally() }
    try body(pasteboard)
}

@MainActor
func copyTestText(_ text: String, to pasteboard: NSPasteboard) {
    pasteboard.clearContents()
    XCTAssertTrue(pasteboard.setString(text, forType: .string))
}

final class ClipboardContentTests: XCTestCase {
    func testChineseEmojiAndMultilineFormattingArePreserved() async {
        await MainActor.run {
            withTestPasteboard { pasteboard in
                let text = "  日常办公 🧺\n\t第二行：请保留缩进\n第三行 👩🏽‍💻\n"
                copyTestText(text, to: pasteboard)
                XCTAssertEqual(ClipboardContent.text(from: pasteboard), text)
            }
        }
    }

    func testWhitespaceOnlyCopiesAreIgnored() async {
        await MainActor.run {
            withTestPasteboard { pasteboard in
                for text in ["", "   ", "\t\n\r ", "\u{00A0}\n"] {
                    copyTestText(text, to: pasteboard)
                    XCTAssertNil(ClipboardContent.text(from: pasteboard))
                }
            }
        }
    }

    func testRTFOnlyCopyBecomesPlainText() async throws {
        try await MainActor.run {
            try withTestPasteboard { pasteboard in
                let text = "中文便签 📝\n保留换行"
                let attributed = NSAttributedString(string: text)
                let rtf = try attributed.data(from: NSRange(location: 0, length: attributed.length),
                                              documentAttributes: [.documentType: NSAttributedString.DocumentType.rtf])
                pasteboard.clearContents()
                XCTAssertTrue(pasteboard.setData(rtf, forType: .rtf))
                // macOS may synthesize .string when it is requested. We only
                // supplied RTF, so successful extraction must handle that input.
                XCTAssertTrue((pasteboard.types ?? []).contains(.rtf))
                XCTAssertEqual(ClipboardContent.text(from: pasteboard), text)
            }
        }
    }

    func testPlainTextTakesPrecedenceOverRTF() async throws {
        try await MainActor.run {
            try withTestPasteboard { pasteboard in
                let richText = NSAttributedString(string: "RTF 内容")
                let rtf = try richText.data(from: NSRange(location: 0, length: richText.length),
                                            documentAttributes: [.documentType: NSAttributedString.DocumentType.rtf])
                copyTestText("用户复制的纯文本", to: pasteboard)
                XCTAssertTrue(pasteboard.setData(rtf, forType: .rtf))
                XCTAssertEqual(ClipboardContent.text(from: pasteboard), "用户复制的纯文本")
            }
        }
    }

    func testURLOnlyCopyCanBeHungAsText() async {
        await MainActor.run {
            withTestPasteboard { pasteboard in
                let url = "https://example.com/office?source=clipboard#notes"
                pasteboard.clearContents()
                XCTAssertTrue(pasteboard.setString(url, forType: .URL))
                XCTAssertEqual(ClipboardContent.text(from: pasteboard), url)
            }
        }
    }

    func testFileURLWithDisplayTextIsIgnored() async {
        await MainActor.run {
            withTestPasteboard { pasteboard in
                copyTestText("预算.xlsx", to: pasteboard)
                XCTAssertTrue(pasteboard.setString("file:///tmp/office-budget.xlsx", forType: .fileURL))
                XCTAssertTrue(ClipboardContent.shouldIgnore(pasteboard))
                XCTAssertNil(ClipboardContent.text(from: pasteboard))
            }
        }
    }

    func testPrivacyAndOwnCopyMarkersAreIgnored() async {
        await MainActor.run {
            withTestPasteboard { pasteboard in
                let markers: [NSPasteboard.PasteboardType] = [
                    ClipboardContent.ownCopyType,
                    .init("org.nspasteboard.ConcealedType"),
                    .init("org.nspasteboard.TransientType"),
                    .init("org.nspasteboard.AutoGeneratedType"),
                    .init("NSFilenamesPboardType"),
                ]
                for marker in markers {
                    copyTestText("不能自动挂出的内容", to: pasteboard)
                    XCTAssertTrue(pasteboard.setData(Data(), forType: marker))
                    XCTAssertTrue(ClipboardContent.shouldIgnore(pasteboard), marker.rawValue)
                    XCTAssertNil(ClipboardContent.text(from: pasteboard), marker.rawValue)
                }
            }
        }
    }

    func testSensitiveMarkerOnAnotherItemIgnoresTheEntireCopy() async {
        await MainActor.run {
            withTestPasteboard { pasteboard in
                let text = NSPasteboardItem()
                XCTAssertTrue(text.setString("看起来是普通文字", forType: .string))
                let protected = NSPasteboardItem()
                XCTAssertTrue(protected.setData(Data(), forType: .init("org.nspasteboard.ConcealedType")))
                pasteboard.clearContents()
                XCTAssertTrue(pasteboard.writeObjects([text, protected]))
                XCTAssertEqual(pasteboard.pasteboardItems?.count, 2)
                XCTAssertTrue(ClipboardContent.shouldIgnore(pasteboard))
                XCTAssertNil(ClipboardContent.text(from: pasteboard))
            }
        }
    }

    func testEmptyOrMalformedRTFPasteboardDoesNotProduceANote() async {
        await MainActor.run {
            withTestPasteboard { pasteboard in
                pasteboard.clearContents()
                XCTAssertNil(ClipboardContent.text(from: pasteboard))
                XCTAssertTrue(pasteboard.setData(Data([0x00, 0xFF, 0x01]), forType: .rtf))
                XCTAssertNil(ClipboardContent.text(from: pasteboard))
            }
        }
    }
}
