import AppKit

/// Interpret a clipboard change without modifying the clipboard or asking
/// another app for its contents. Also respect the standard privacy markers.
@MainActor
enum ClipboardContent {
    static let ownCopyType = NSPasteboard.PasteboardType("app.snapline.Snapline.own-copy")

    /// UI test bundles use the same isolated clipboard for capture and takeout.
    /// Shipping builds always use the user's normal clipboard.
    static var transferPasteboard: NSPasteboard {
        #if DEBUG
        if let name = Bundle.main.object(forInfoDictionaryKey: "SnaplineDiagnosticPasteboard") as? String {
            return NSPasteboard(name: .init(name))
        }
        #endif
        return .general
    }

    /// Images may be copied as local files. Privacy and our own transfer
    /// markers still apply to the entire clipboard, including other items.
    static func shouldIgnoreImages(_ pasteboard: NSPasteboard) -> Bool {
        let types = Set((pasteboard.types ?? []) + (pasteboard.pasteboardItems ?? []).flatMap(\.types))
        let ignored: Set<NSPasteboard.PasteboardType> = [
            ownCopyType,
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        ]
        return !types.isDisjoint(with: ignored)
    }

    static func shouldIgnore(_ pasteboard: NSPasteboard) -> Bool {
        let types = Set((pasteboard.types ?? []) + (pasteboard.pasteboardItems ?? []).flatMap(\.types))
        let ignored: Set<NSPasteboard.PasteboardType> = [
            ownCopyType, .fileURL,
            NSPasteboard.PasteboardType("NSFilenamesPboardType"),
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        ]
        return !types.isDisjoint(with: ignored)
    }

    static func text(from pasteboard: NSPasteboard) -> String? {
        guard !shouldIgnore(pasteboard) else { return nil }
        let text: String?
        if let plain = pasteboard.string(forType: .string) {
            text = plain
        } else if let rtf = pasteboard.data(forType: .rtf),
                  let attributed = try? NSAttributedString(data: rtf, options: [.documentType: NSAttributedString.DocumentType.rtf], documentAttributes: nil) {
            text = attributed.string
        } else {
            text = pasteboard.string(forType: .URL)
        }
        guard let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        // Keep the original indentation, newlines and Unicode characters.
        return text
    }
}
